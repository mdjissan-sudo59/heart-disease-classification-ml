import warnings
warnings.filterwarnings("ignore")

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns

from sklearn.model_selection import train_test_split, StratifiedKFold, cross_validate, GridSearchCV
from sklearn.compose import ColumnTransformer
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import OneHotEncoder, StandardScaler
from sklearn.impute import SimpleImputer
from sklearn.linear_model import LogisticRegression
from sklearn.tree import DecisionTreeClassifier
from sklearn.neighbors import KNeighborsClassifier
from sklearn.ensemble import RandomForestClassifier, GradientBoostingClassifier
from sklearn.metrics import (
    accuracy_score, precision_score, recall_score, f1_score,
    confusion_matrix, classification_report, roc_auc_score,
    roc_curve, ConfusionMatrixDisplay
)
from sklearn.inspection import permutation_importance

RANDOM_STATE = 42
pd.set_option("display.max_columns", None)
sns.set_theme(style="whitegrid")
print("Libraries imported successfully.")

DATA_URL = "https://archive.ics.uci.edu/ml/machine-learning-databases/heart-disease/processed.cleveland.data"
COLUMN_NAMES = [
    "age", "sex", "cp", "trestbps", "chol", "fbs", "restecg",
    "thalach", "exang", "oldpeak", "slope", "ca", "thal", "target"
]

try:
    df = pd.read_csv(DATA_URL, header=None, names=COLUMN_NAMES)
    print("Dataset downloaded from UCI.")
except Exception as error:
    print("Online download failed:", error)
    DATA_PATH = "processed.cleveland.data"  # Put the downloaded file in the notebook folder
    df = pd.read_csv(DATA_PATH, header=None, names=COLUMN_NAMES)

df.head()

print("Number of rows:", df.shape[0])
print("Number of columns:", df.shape[1])
print("\\nColumn names:")
print(df.columns.tolist())
print("\\nData types:")
print(df.dtypes)
print("\\nDataset information:")
df.info()

df = df.replace("?", np.nan)
for column in df.columns:
    df[column] = pd.to_numeric(df[column], errors="coerce")

print("Missing values in each column:")
display(df.isnull().sum().to_frame("missing_count"))

print("Original target values:")
print(df["target"].value_counts(dropna=False).sort_index())

df = df.dropna(subset=["target"]).copy()
df["target"] = (df["target"] > 0).astype(int)

print("\\nBinary target counts:")
print(df["target"].value_counts())
print("\\nBinary target percentages:")
print((df["target"].value_counts(normalize=True) * 100).round(2))

display(df.describe().T)

missing_summary = pd.DataFrame({
    "Missing Count": df.isnull().sum(),
    "Missing Percentage": (df.isnull().mean() * 100).round(2)
})
display(missing_summary)

plt.figure(figsize=(6, 4))
sns.countplot(data=df, x="target")
plt.title("Heart Disease Target Distribution")
plt.xlabel("Target (0 = absent, 1 = present)")
plt.ylabel("Number of records")
plt.show()

df.hist(figsize=(16, 12), bins=20, edgecolor="black")
plt.suptitle("Feature Distributions", y=1.02)
plt.tight_layout()
plt.show()

numeric_columns = df.drop(columns=["target"]).select_dtypes(include=np.number).columns

outlier_rows = []
for column in numeric_columns:
    q1 = df[column].quantile(0.25)
    q3 = df[column].quantile(0.75)
    iqr = q3 - q1
    lower = q1 - 1.5 * iqr
    upper = q3 + 1.5 * iqr
    count = ((df[column] < lower) | (df[column] > upper)).sum()
    outlier_rows.append([column, lower, upper, int(count)])

outlier_summary = pd.DataFrame(
    outlier_rows, columns=["Feature", "Lower Bound", "Upper Bound", "Outlier Count"]
)
display(outlier_summary)

plt.figure(figsize=(16, 7))
sns.boxplot(data=df[numeric_columns], orient="h")
plt.title("Boxplots for Numerical Features")
plt.tight_layout()
plt.show()

plt.figure(figsize=(12, 9))
sns.heatmap(df.corr(numeric_only=True), annot=True, cmap="coolwarm", fmt=".2f")
plt.title("Feature Correlation Heatmap")
plt.tight_layout()
plt.show()

categorical_features = ["sex", "cp", "fbs", "restecg", "exang", "slope", "ca", "thal"]
numeric_features = ["age", "trestbps", "chol", "thalach", "oldpeak"]

print("Numerical features:", numeric_features)
print("Categorical features:", categorical_features)
print("Target: target")

X = df.drop(columns=["target"])
y = df["target"]

X_train, X_test, y_train, y_test = train_test_split(
    X, y, test_size=0.30, random_state=RANDOM_STATE, stratify=y
)

print("Training feature shape:", X_train.shape)
print("Testing feature shape:", X_test.shape)
print("Training target distribution:")
print(y_train.value_counts(normalize=True).round(3))
print("Testing target distribution:")
print(y_test.value_counts(normalize=True).round(3))

numeric_transformer = Pipeline(steps=[
    ("imputer", SimpleImputer(strategy="median")),
    ("scaler", StandardScaler())
])

categorical_transformer = Pipeline(steps=[
    ("imputer", SimpleImputer(strategy="most_frequent")),
    ("onehot", OneHotEncoder(handle_unknown="ignore"))
])

preprocessor = ColumnTransformer(transformers=[
    ("num", numeric_transformer, numeric_features),
    ("cat", categorical_transformer, categorical_features)
])
print("Preprocessing pipeline created.")

baseline_models = {
    "Logistic Regression": LogisticRegression(max_iter=2000, class_weight="balanced"),
    "Decision Tree": DecisionTreeClassifier(random_state=RANDOM_STATE, class_weight="balanced"),
    "KNN": KNeighborsClassifier(n_neighbors=5)
}

baseline_pipelines = {
    name: Pipeline(steps=[("preprocessor", preprocessor), ("model", model)])
    for name, model in baseline_models.items()
}

baseline_results = []
for name, pipeline in baseline_pipelines.items():
    pipeline.fit(X_train, y_train)
    predictions = pipeline.predict(X_test)
    baseline_results.append({
        "Model": name,
        "Accuracy": accuracy_score(y_test, predictions),
        "Precision": precision_score(y_test, predictions, zero_division=0),
        "Recall": recall_score(y_test, predictions, zero_division=0),
        "F1 Score": f1_score(y_test, predictions, zero_division=0)
    })

baseline_table = pd.DataFrame(baseline_results).sort_values("F1 Score", ascending=False)
display(baseline_table.round(3))

for name, pipeline in baseline_pipelines.items():
    predictions = pipeline.predict(X_test)
    print("\\n", name)
    print(classification_report(y_test, predictions, zero_division=0))
    ConfusionMatrixDisplay.from_predictions(y_test, predictions, cmap="Blues")
    plt.title(f"Confusion Matrix – {name}")
    plt.show()

advanced_models = {
    "Random Forest": RandomForestClassifier(
        n_estimators=300, random_state=RANDOM_STATE, class_weight="balanced"
    ),
    "Gradient Boosting": GradientBoostingClassifier(random_state=RANDOM_STATE)
}

advanced_pipelines = {
    name: Pipeline(steps=[("preprocessor", preprocessor), ("model", model)])
    for name, model in advanced_models.items()
}

advanced_results = []
for name, pipeline in advanced_pipelines.items():
    pipeline.fit(X_train, y_train)
    predictions = pipeline.predict(X_test)
    advanced_results.append({
        "Model": name,
        "Accuracy": accuracy_score(y_test, predictions),
        "Precision": precision_score(y_test, predictions, zero_division=0),
        "Recall": recall_score(y_test, predictions, zero_division=0),
        "F1 Score": f1_score(y_test, predictions, zero_division=0)
    })

advanced_table = pd.DataFrame(advanced_results).sort_values("F1 Score", ascending=False)
display(advanced_table.round(3))

all_results = pd.concat([baseline_table, advanced_table], ignore_index=True)
all_results = all_results.sort_values("F1 Score", ascending=False).reset_index(drop=True)
display(all_results.round(3))

cv = StratifiedKFold(n_splits=5, shuffle=True, random_state=RANDOM_STATE)
scoring = {"accuracy": "accuracy", "precision": "precision", "recall": "recall", "f1": "f1", "roc_auc": "roc_auc"}

cv_rows = []
for name, pipeline in {**baseline_pipelines, **advanced_pipelines}.items():
    scores = cross_validate(pipeline, X_train, y_train, cv=cv, scoring=scoring, n_jobs=-1)
    cv_rows.append({
        "Model": name,
        "CV Accuracy": scores["test_accuracy"].mean(),
        "CV Precision": scores["test_precision"].mean(),
        "CV Recall": scores["test_recall"].mean(),
        "CV F1": scores["test_f1"].mean(),
        "CV ROC-AUC": scores["test_roc_auc"].mean()
    })

cv_table = pd.DataFrame(cv_rows).sort_values("CV F1", ascending=False)
display(cv_table.round(3))

rf_pipeline = Pipeline(steps=[
    ("preprocessor", preprocessor),
    ("model", RandomForestClassifier(random_state=RANDOM_STATE, class_weight="balanced"))
])

param_grid = {
    "model__n_estimators": [100, 200, 300],
    "model__max_depth": [None, 4, 8],
    "model__min_samples_split": [2, 5],
    "model__min_samples_leaf": [1, 2]
}

grid_search = GridSearchCV(
    estimator=rf_pipeline,
    param_grid=param_grid,
    scoring="f1",
    cv=cv,
    n_jobs=-1,
    verbose=1
)
grid_search.fit(X_train, y_train)

print("Best parameters:", grid_search.best_params_)
print("Best mean CV F1:", round(grid_search.best_score_, 3))
best_model = grid_search.best_estimator_

tuned_predictions = best_model.predict(X_test)
tuned_probabilities = best_model.predict_proba(X_test)[:, 1]

tuned_metrics = {
    "Accuracy": accuracy_score(y_test, tuned_predictions),
    "Precision": precision_score(y_test, tuned_predictions, zero_division=0),
    "Recall": recall_score(y_test, tuned_predictions, zero_division=0),
    "F1 Score": f1_score(y_test, tuned_predictions, zero_division=0),
    "ROC-AUC": roc_auc_score(y_test, tuned_probabilities)
}
display(pd.DataFrame([tuned_metrics]).round(3))
print(classification_report(y_test, tuned_predictions, zero_division=0))

fpr, tpr, thresholds = roc_curve(y_test, tuned_probabilities)
auc_value = roc_auc_score(y_test, tuned_probabilities)

plt.figure(figsize=(7, 5))
plt.plot(fpr, tpr, label=f"Tuned Random Forest (AUC = {auc_value:.3f})")
plt.plot([0, 1], [0, 1], linestyle="--", label="Random classifier")
plt.xlabel("False Positive Rate")
plt.ylabel("True Positive Rate")
plt.title("ROC Curve – Tuned Random Forest")
plt.legend()
plt.show()
print("ROC-AUC:", round(auc_value, 3))

print("Training class counts:")
display(y_train.value_counts().rename(index={0: "No disease", 1: "Disease"}).to_frame("Count"))
print("Training class percentages:")
display((y_train.value_counts(normalize=True) * 100).round(2).to_frame("Percentage"))

validation_summary = pd.DataFrame([{
    "Best CV F1": grid_search.best_score_,
    "Test F1": f1_score(y_test, tuned_predictions),
    "Test ROC-AUC": auc_value
}])
display(validation_summary.round(3))

error_analysis = X_test.copy()
error_analysis["Actual"] = y_test
error_analysis["Predicted"] = tuned_predictions
error_analysis["Predicted_Probability"] = tuned_probabilities
error_analysis["Error_Type"] = np.select(
    [
        (error_analysis["Actual"] == 1) & (error_analysis["Predicted"] == 0),
        (error_analysis["Actual"] == 0) & (error_analysis["Predicted"] == 1)
    ],
    ["False Negative", "False Positive"],
    default="Correct"
)
display(error_analysis[error_analysis["Error_Type"] != "Correct"].sort_values("Predicted_Probability").head(15))
print(error_analysis["Error_Type"].value_counts())

threshold_rows = []
for threshold in [0.30, 0.40, 0.50, 0.60, 0.70]:
    threshold_predictions = (tuned_probabilities >= threshold).astype(int)
    threshold_rows.append({
        "Threshold": threshold,
        "Accuracy": accuracy_score(y_test, threshold_predictions),
        "Precision": precision_score(y_test, threshold_predictions, zero_division=0),
        "Recall": recall_score(y_test, threshold_predictions, zero_division=0),
        "F1": f1_score(y_test, threshold_predictions, zero_division=0)
    })

threshold_table = pd.DataFrame(threshold_rows)
display(threshold_table.round(3))

print("Random state:", RANDOM_STATE)
print("Training rows:", len(X_train))
print("Testing rows:", len(X_test))
print("Best model:", best_model.named_steps["model"])
print("Best parameters:", grid_search.best_params_)

final_comparison = all_results.copy()
final_comparison.loc[len(final_comparison)] = {
    "Model": "Tuned Random Forest",
    "Accuracy": tuned_metrics["Accuracy"],
    "Precision": tuned_metrics["Precision"],
    "Recall": tuned_metrics["Recall"],
    "F1 Score": tuned_metrics["F1 Score"]
}
final_comparison = final_comparison.sort_values("F1 Score", ascending=False).reset_index(drop=True)
display(final_comparison.round(3))

perm = permutation_importance(
    best_model, X_test, y_test,
    n_repeats=20, random_state=RANDOM_STATE,
    scoring="f1", n_jobs=-1
)
importance_df = pd.DataFrame({
    "Feature": X_test.columns,
    "Importance Mean": perm.importances_mean,
    "Importance Std": perm.importances_std
}).sort_values("Importance Mean", ascending=False)

display(importance_df)

plt.figure(figsize=(9, 6))
sns.barplot(data=importance_df, x="Importance Mean", y="Feature")
plt.title("Permutation Feature Importance – Tuned Random Forest")
plt.xlabel("Mean decrease in F1 score when shuffled")
plt.ylabel("Feature")
plt.tight_layout()
plt.show()

